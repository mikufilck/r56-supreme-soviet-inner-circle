def block_end(text: str, opening: int) -> int:
    depth = 0
    quoted = False
    commented = False
    for i in range(opening, len(text)):
        c = text[i]
        if c == "\n":
            commented = False
            continue
        if commented:
            continue
        if c == '"':
            quoted = not quoted
            continue
        if quoted:
            continue
        if c == "#":
            commented = True
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("Unclosed MIO organization block")


def trait_text(spec: dict[str, object]) -> str:
    out = [
        "\t# hof: Tukhachevsky / air mechanization",
        "\tadd_trait = {",
        f"\t\ttoken = {spec['trait']}",
        f"\t\tname = {spec['trait']}",
        f"\t\ticon = {spec['icon']}",
        "\t\tspecial_trait_background = yes",
        "\t\tposition = { x=9 y=0 }",
        "\t\tvisible = { FROM = { original_tag = SOV } }",
        "\t\tavailable = { FROM = { has_completed_focus = hof_ic_tukhachevsky_air_mechanization } }",
    ]
    if spec.get("limit"):
        out.append(f"\t\tlimit_to_equipment_type = {{ {spec['limit']} }}")
    out.append("\t\tequipment_bonus = {")
    for stat, value in spec["stats"].items():
        out.append(f"\t\t\t{stat} = {value:.2f}")
    out.extend(("\t\t}", "\t}"))
    return "\n".join(out)


def generate_organizations() -> None:
    source = SOURCE.read_text(encoding="utf-8-sig")
    text = source
    for spec in TRAITS:
        pattern = re.compile(rf"(?m)^{re.escape(spec['org'])}\s*=\s*\{{")
        hits = list(pattern.finditer(text))
        if len(hits) != 1:
            raise ValueError(f"Expected one R56 organization {spec['org']}, got {len(hits)}")
        end = block_end(text, text.index("{", hits[0].start()))
        text = text[:end] + trait_text(spec) + "\n" + text[end:]
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    for spec in TRAITS:
        if text.count(f"token = {spec['trait']}") != 1:
            raise ValueError(f"Trait missing or duplicated: {spec['trait']}")


def generate_effects() -> None:
    effect = MOD / "common/scripted_effects/hof_ic_mio_effects.txt"
    action = MOD / "common/on_actions/hof_ic_mio_on_actions.txt"
    lines = [
        "# Generated by build/gen-hof-ic-mio.py; R56 organization definitions are the base.",
        "hof_ic_tukh_mio_air_mechanization = {",
        "\tif = {",
        '\t\tlimit = { has_dlc = "Arms Against Tyranny" }',
    ]
    for spec in TRAITS:
        lines.extend(
            (
                f"\t\tmio:{spec['org']} = {{",
                f"\t\t\tif = {{ limit = {{ NOT = {{ is_mio_trait_completed = {spec['trait']} }} }}",
                f"\t\t\t\tcomplete_mio_trait = {spec['trait']}",
                "\t\t\t}",
                "\t\t}",
            )
        )
    lines.extend(("\t}", "}"))
    effect.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    action.write_text(
        "# Existing saves: grant the focus trait on the first weekly tick.\n"
        "on_actions = {\n"
        "\ton_weekly = { effect = {\n"
        "\t\tif = { limit = { tag = SOV has_completed_focus = hof_ic_tukhachevsky_air_mechanization }\n"
        "\t\t\thof_ic_tukh_mio_air_mechanization = yes\n"
        "\t\t}\n"
        "\t} }\n"
        "}\n",
        encoding="utf-8",
        newline="\n",
    )


def generate_localisation() -> None:
    path = MOD / "localisation/simp_chinese/hof_ic_mio_l_simp_chinese.yml"
    lines = ["l_simp_chinese:"]
